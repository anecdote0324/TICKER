export interface FunctionDef {
  code: string;
  nameKo: string;
  nameEn: string;
  /** 후보 줄에 보이는 한 줄 설명 */
  summary: string;
  /** 설명 창에 보이는 긴 설명 */
  detail?: string;
  security: SecurityNeed;
  /** 종목이 필요한 기능이 지원하는 자산군 */
  assetClasses: AssetClass[];
  /** 분봉 같은 특별한 데이터가 필요한지. 소스가 주지 않으면 그 종목에서 빠져요(05 §3.4) */
  needs?: Array<'intraday'>;
  /** 한국어 키워드(05 §12.3). 첫 번째 키워드가 대표예요 */
  keywords: string[];
  /** 'v0.1' 같은 단계 */
  version: string;
  implemented: boolean;
  /** 데이터 속도(02 신선도 표시와 같은 말) */
  speed: string;
  examples: string[];
  similar?: string[];
  /** 대표 기능의 탭으로 여는 블룸버그 별칭 */
  aliases?: string[];
  /** 블룸버그 코드가 아닌 자체 코드(K 접두) */
  notBloomberg?: boolean;
  approx?: boolean;
  /** 기능 뒤에 붙이는 인자 */
  args?: FunctionArgs;
}

